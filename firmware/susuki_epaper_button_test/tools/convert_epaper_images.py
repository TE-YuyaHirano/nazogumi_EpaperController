#!/usr/bin/env python3
"""Convert the open/closed eye artwork into packed Spectra 6 panel data."""

from pathlib import Path

import numpy as np
from PIL import Image, ImageEnhance, ImageOps


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
HEADER = ROOT / "epaper_portraits.h"

# Artwork is prepared in the panel's mounted portrait orientation, then rotated
# counter-clockwise into the controller's native 800 x 480 memory order.
WIDTH = 480
HEIGHT = 800

# Preview RGB values and the corresponding 4-bit values expected by EPD_7in3e.
PALETTE = np.array(
    [
        [0, 0, 0],        # black
        [255, 255, 255],  # white
        [255, 214, 0],    # yellow
        [205, 20, 20],    # red
        [20, 90, 180],    # blue
        [20, 135, 70],    # green
    ],
    dtype=np.float32,
)
EPD_CODES = np.array([0x0, 0x1, 0x2, 0x3, 0x5, 0x6], dtype=np.uint8)


def prepare(source: Path) -> Image.Image:
    image = Image.open(source).convert("RGB")
    image = ImageOps.fit(image, (WIDTH, HEIGHT), method=Image.Resampling.LANCZOS)
    # These assets are monochrome line art on slightly warm paper.  A clean
    # threshold prevents the paper tint from becoming yellow dither noise.
    gray = ImageOps.grayscale(image)
    return gray.point(lambda value: 255 if value >= 210 else 0).convert("RGB")


def dither(image: Image.Image) -> tuple[np.ndarray, Image.Image]:
    pixels = np.asarray(image, dtype=np.float32).copy()
    indices = np.zeros((HEIGHT, WIDTH), dtype=np.uint8)

    # Floyd-Steinberg diffusion with a perceptual green-channel weighting.
    weights = np.array([0.30, 0.59, 0.11], dtype=np.float32)
    for y in range(HEIGHT):
        for x in range(WIDTH):
            old = np.clip(pixels[y, x], 0, 255)
            distances = np.sum(((PALETTE - old) ** 2) * weights, axis=1)
            index = int(np.argmin(distances))
            indices[y, x] = index
            error = old - PALETTE[index]
            if x + 1 < WIDTH:
                pixels[y, x + 1] += error * (7 / 16)
            if y + 1 < HEIGHT:
                if x > 0:
                    pixels[y + 1, x - 1] += error * (3 / 16)
                pixels[y + 1, x] += error * (5 / 16)
                if x + 1 < WIDTH:
                    pixels[y + 1, x + 1] += error * (1 / 16)

    preview = Image.fromarray(PALETTE[indices].astype(np.uint8), mode="RGB")
    return EPD_CODES[indices], preview


def rotate_and_pack(portrait_codes: np.ndarray) -> bytes:
    physical = np.rot90(portrait_codes, k=1)
    packed = (physical[:, 0::2] << 4) | physical[:, 1::2]
    return packed.astype(np.uint8).tobytes()


def array_text(name: str, data: bytes) -> str:
    lines = []
    for start in range(0, len(data), 24):
        chunk = data[start : start + 24]
        lines.append("  " + ", ".join(f"0x{value:02X}" for value in chunk) + ",")
    return f"const uint8_t {name}[{len(data)}] PROGMEM = {{\n" + "\n".join(lines) + "\n};\n"


def convert(stem: str, array_name: str) -> tuple[str, int]:
    source = ASSETS / f"me_{stem}.jpg"
    portrait = prepare(source)
    codes, preview = dither(portrait)
    preview.save(ASSETS / f"me_{stem}_mounted_preview.png")
    preview.rotate(90, expand=True).save(
        ASSETS / f"me_{stem}_controller_preview.png"
    )
    data = rotate_and_pack(codes)
    return array_text(array_name, data), len(data)


def main() -> None:
    open_array, open_size = convert("open", "EPD_IMAGE_OPEN")
    closed_array, closed_size = convert("close", "EPD_IMAGE_CLOSED")
    if open_size != 192000 or closed_size != 192000:
        raise RuntimeError("Unexpected packed image size")

    HEADER.write_text(
        "#pragma once\n\n"
        "#include <Arduino.h>\n\n"
        "// Generated by tools/convert_epaper_images.py; two pixels per byte.\n"
        + open_array
        + "\n"
        + closed_array,
        encoding="utf-8",
    )
    print(f"Wrote {HEADER} ({open_size + closed_size} image bytes)")


if __name__ == "__main__":
    main()
